import { ref } from 'vue'
import { LibraryService } from '~/services/libraryService'

export const useLibrary = () => {
    const token = ref<string|null>(
        import.meta.client ? localStorage.getItem('access_token') : null
    )
    const error = ref<string>('');
    const isLoading = ref<boolean>(false);
    const rulebooks = ref<any[]>([]);
    const currentRulebook = ref<any>(null);

    const fetchAllRulebooks = async () => {
        
        error.value = '';
        isLoading.value = true;

        try {
            const response = await LibraryService.getAllRulebooks();
            
            // The 'content' array is generated by Spring Boot's Page object
            rulebooks.value = response.data.content.map((rulebook: any) => ({
                ...rulebook,
                title: rulebook.gameName
            })); 
            //console.log('fetched:', rulebooks.value);
            console.log('keys:', Object.keys(rulebooks.value[0] || {}));


            
        } catch(err: any) {
            error.value = err.response?.data?.message || 'No rulebooks found'
            rulebooks.value = []
        } finally {
            isLoading.value = false;
        }
    }

    const fetchRulebookById = async (id: string) => {
        error.value = '';
        isLoading.value = true;
        currentRulebook.value = null;

        try{
            currentRulebook.value = await LibraryService.getRulebookById(id);
        }catch(err: any){
            console.error(`Failed to fetch rulebook ${id}:`, err);
            error.value = err.response?.data?.message || 'Failed to load rulebook details';
        }finally{
            isLoading.value = false;
        }
    }

    const rulebookText = ref<any>(null)

    const fetchRulebookText = async (id: string) => {
        try {
            const response = await LibraryService.getRulebookText(id)
            rulebookText.value = response.data
        } catch (err: any) {
            console.error(`Failed to fetch rulebook text ${id}:`, err)
            rulebookText.value = null
        }
    }

    return {
        token,
        error,
        isLoading,
        rulebooks,
        rulebookText,
        fetchAllRulebooks,
        fetchRulebookById,
        fetchRulebookText
    }
}